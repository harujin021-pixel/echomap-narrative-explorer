"""AI 文案生成界面（mock 模式）的 AppTest 端到端测试。

用 Streamlit 官方 testing 框架驱动真实 app.py，覆盖：
    - mock 模式警示可见；
    - 生成按钮 -> 编辑框出现带【模拟响应】标记的占位文案；
    - 编辑后只读复制块同步（AppTest 的 set_value 等价于真实用户输入+失焦）；
    - 切换平台后文案不残留、切回后编辑内容保留（会话状态按平台+选题隔离）；
    - 全程无 error / exception。
"""

import unittest
from pathlib import Path

from streamlit.testing.v1 import AppTest

PROJECT_ROOT = Path(__file__).resolve().parents[1]
APP_PATH = PROJECT_ROOT / "app" / "app.py"
MOCK_PREFIX = "【模拟响应"
EDIT_MARK = "USER_EDIT_TEST_123"


class CopywritingUITest(unittest.TestCase):
    def setUp(self):
        at = AppTest.from_file(APP_PATH, default_timeout=120)
        at.run()
        # 加载内置合成演示数据（与界面按钮同一入口）
        at.sidebar.button(key="demo_btn").click().run()
        # 切换到 AI 推荐选题页
        at.sidebar.radio(key="page_radio").set_value("strategist").run()
        self.at = at

    def _selectbox(self, prefix):
        matches = [sb for sb in self.at.selectbox if sb.key.startswith(prefix)]
        self.assertEqual(
            len(matches), 1, f"期望 1 个 {prefix} 选择器: {[sb.key for sb in self.at.selectbox]}"
        )
        return matches[0]

    def _text_area(self, prefix):
        matches = [ta for ta in self.at.text_area if ta.key.startswith(prefix)]
        self.assertEqual(len(matches), 1, f"期望 1 个 {prefix} 编辑框")
        return matches[0]

    def _button(self, prefix):
        matches = [b for b in self.at.button if b.key.startswith(prefix)]
        self.assertEqual(len(matches), 1, f"期望 1 个 {prefix} 按钮")
        return matches[0]

    def test_mock_warning_visible(self):
        # 应用默认英文界面（i18n DEFAULT_LANG = "en"），断言英文警示文案
        warnings_text = " ".join(w.value for w in self.at.warning)
        self.assertIn("Mock mode", warnings_text)
        self.assertIn("NOT generated by any AI model", warnings_text)

    def test_generate_edit_and_platform_switch_flow(self):
        at = self.at

        # 1) 生成模拟文案
        self._button("cp_btn_").click().run()
        editor = self._text_area("cp_w_")
        self.assertTrue(editor.value.startswith(MOCK_PREFIX))
        self.assertIn("== 笔记标题 ==", editor.value)

        # 2) 编辑内容同步到只读复制块（等价真实输入+失焦）
        editor.set_value(editor.value + "\n" + EDIT_MARK).run()
        code_bodies = [c.value for c in at.code]
        self.assertTrue(
            any(EDIT_MARK in body for body in code_bodies),
            "编辑后的文案应同步出现在只读复制块中",
        )

        # 3) 切换平台 -> 编辑框清空，不残留
        self._selectbox("cp_platform_").set_value("weibo").run()
        self.assertEqual(self._text_area("cp_w_").value, "")

        # 4) 切回小红书 -> 之前的编辑内容保留
        self._selectbox("cp_platform_").set_value("xiaohongshu").run()
        self.assertIn(EDIT_MARK, self._text_area("cp_w_").value)

        # 5) 提示词预览可展开且包含事实边界指令
        prompt_codes = [c.value for c in at.code]
        self.assertTrue(any("不得编造" in body for body in prompt_codes))

        # 6) 全程无错误
        self.assertEqual(len(at.error), 0)
        self.assertEqual(len(at.exception), 0)


    def test_safety_pass_enables_export(self):
        # 干净的模拟文案应通过本地检测：显示成功提示，只读复制块可用
        at = self.at
        self._button("cp_btn_").click().run()
        successes = " ".join(s.value for s in at.success)
        self.assertIn("PASSED", successes)
        self.assertTrue(
            any(MOCK_PREFIX in c.value for c in at.code),
            "通过检测后应显示可导出的只读复制块",
        )
        self.assertEqual(len(at.error), 0)

    def test_safety_fail_disables_export(self):
        # 文案含手机号 -> 判定未通过：报错提示，且不得出现可导出的原始文案
        at = self.at
        self._button("cp_btn_").click().run()
        self._text_area("cp_w_").set_value("联系方式 13812345678 请勿外传").run()
        errors = " ".join(e.value for e in at.error)
        self.assertIn("NOT PASSED", errors)
        self.assertFalse(
            any("13812345678" in c.value for c in at.code),
            "未通过检测时不得导出原始文案",
        )


if __name__ == "__main__":
    unittest.main()
